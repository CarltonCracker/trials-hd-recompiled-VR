#!/usr/bin/env bash
# Rebuild the SDK's full resolve compute shaders (SPIR-V headers in
# thirdparty/rexglue-sdk/src/graphics/shaders/xesl/vulkan_spirv/, included by
# the Vulkan render target cache instead of the stock ones) from the XeSL
# sources in thirdparty/rexglue-sdk/src/graphics/shaders/xesl/ - Xenia's
# resolve shaders with the Trials HD fix (number-format-aware k_16_16 /
# k_16_16_16_16 packing). Same steps as Xenia's
# `xb buildshaders` (glslangValidator, spirv-opt -O --canonicalize-ids), but
# without the disassembly comment block to keep the SDK patch small.
#
# glslang and spirv-tools are built from the SDK's thirdparty sources into
# out/shader-tools on first use. The generated headers are part of the SDK
# patch (tools/export_sdk_patch.sh), so this only needs to run after editing
# the shader sources.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
sdk="$root/thirdparty/rexglue-sdk"
src="$sdk/src/graphics/shaders/xesl"
dst="$sdk/src/graphics/shaders/xesl/vulkan_spirv"
mkdir -p "$dst"
tools="$root/out/shader-tools"
work="$tools/work"

build_tool() {  # <source dir> <build dir> <target...> -- <cmake args...>
  local source="$1" build="$2"
  shift 2
  local targets=()
  while [ "$1" != "--" ]; do targets+=("$1"); shift; done
  shift
  if [ ! -f "$build/build.ninja" ]; then
    cmake -S "$source" -B "$build" -G Ninja -DCMAKE_BUILD_TYPE=Release \
      -DCMAKE_C_COMPILER=clang -DCMAKE_CXX_COMPILER=clang++ "$@" > /dev/null
  fi
  cmake --build "$build" --target "${targets[@]}" > /dev/null
}

build_tool "$sdk/thirdparty/glslang" "$tools/glslang" glslangValidator -- \
  -DENABLE_OPT=OFF -DGLSLANG_TESTS=OFF -DENABLE_HLSL=OFF -DBUILD_EXTERNAL=OFF
build_tool "$sdk/thirdparty/spirv-tools" "$tools/spirv-tools" spirv-opt -- \
  -DSPIRV-Headers_SOURCE_DIR="$sdk/thirdparty/spirv-headers" -DSPIRV_SKIP_TESTS=ON \
  -DSPIRV_WERROR=OFF
glslang="$tools/glslang/StandAlone/glslangValidator"
spirv_opt="$tools/spirv-tools/tools/spirv-opt"

mkdir -p "$work"
for source in "$src"/resolve_full_*.cs.xesl; do
  name="$(basename "$source" .xesl)"   # resolve_full_32bpp.cs
  id="${name//./_}"                    # resolve_full_32bpp_cs
  printf '#version 460\n#extension GL_EXT_control_flow_attributes : require\n#extension GL_EXT_samplerless_texture_functions : require\n#extension GL_GOOGLE_include_directive : require\n#include "%s"\n' \
    "$(basename "$source")" |
    "$glslang" --stdin -DSHADING_LANGUAGE_GLSL_XE=1 -S comp -o "$work/$id.glslang.spv" -V \
      -I"$src" > "$work/$id.log" || { cat "$work/$id.log"; exit 1; }
  "$spirv_opt" -O --canonicalize-ids "$work/$id.glslang.spv" -o "$work/$id.spv"
  python3 - "$work/$id.spv" "$dst/$id.h" "$id" <<'EOF'
import struct, sys
spv, out, ident = sys.argv[1:4]
data = open(spv, "rb").read()
words = struct.unpack(f"<{len(data) // 4}I", data)
with open(out, "w") as f:
    f.write("// Generated by tools/build_resolve_shaders.sh (Trials HD) from\n"
            "// src/graphics/shaders/xesl - do not edit.\n\n")
    f.write(f"const uint32_t {ident}[] = {{")
    for i, w in enumerate(words):
        f.write("\n    " if i % 8 == 0 else " ")
        f.write(f"0x{w:08X},")
    f.write("\n};\n")
EOF
  echo "built $id"
done
