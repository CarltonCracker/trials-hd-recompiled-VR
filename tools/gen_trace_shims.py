#!/usr/bin/env python3
"""Generate call-counting wrappers for recompiled functions in an address range.

Every recompiled function is a weak symbol, so a strong definition in the app
replaces it; the wrapper bumps a counter and calls the original (__imp__ name).
Used with -DTRIALSHD_CALL_TRACE=ON to find which game functions run per draw /
per frame (see docs/d3d-map.md). Only addresses are written, no game code.

Usage: gen_trace_shims.py <generated/default dir> <src dir> <out.cpp> <lo> <hi>
  lo/hi: hex address range, e.g. 0x8212B000 0x82170000
"""
import os
import re
import sys


def main():
    if len(sys.argv) != 6:
        raise SystemExit(__doc__)
    gen_dir, src_dir, out_path = sys.argv[1:4]
    lo, hi = int(sys.argv[4], 16), int(sys.argv[5], 16)

    funcs = set()
    for name in os.listdir(gen_dir):
        if name.endswith("_register.cpp"):
            with open(os.path.join(gen_dir, name)) as f:
                funcs |= {int(m, 16) for m in re.findall(r"SetFunction\(0x([0-9A-Fa-f]+)", f.read())}

    # Functions the port already overrides must not get a second definition.
    overridden = set()
    for root, _, files in os.walk(src_dir):
        for name in files:
            if name.endswith((".cpp", ".h")):
                with open(os.path.join(root, name)) as f:
                    overridden |= {int(m, 16) for m in re.findall(r"REX_FUNC\(sub_([0-9A-Fa-f]{8})\)", f.read())}

    traced = sorted(a for a in funcs if lo <= a < hi and a not in overridden)
    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    with open(out_path, "w") as f:
        f.write("// Generated by tools/gen_trace_shims.py -- do not edit.\n")
        f.write(f"// {len(traced)} functions in [0x{lo:08X}, 0x{hi:08X}).\n\n")
        f.write('#include "diag/call_trace.h"\n\n#include <rex/ppc/context.h>\n#include <rex/ppc/func.h>\n\n')
        f.write("#define TRACE_SHIM(index, name)                                  \\\n"
                "  REX_EXTERN(__imp__##name);                                     \\\n"
                "  extern \"C\" REX_FUNC(name) {                                   \\\n"
                "    trials_hd::diag::g_call_counts[index].fetch_add(1, std::memory_order_relaxed); \\\n"
                "    if (trials_hd::diag::g_capture_args[index].load(std::memory_order_relaxed)) \\\n"
                "      trials_hd::diag::CaptureArgs(index, ctx);                  \\\n"
                "    __imp__##name(ctx, base);                                    \\\n"
                "  }\n\n")
        for i, a in enumerate(traced):
            f.write(f"TRACE_SHIM({i}, sub_{a:08X})\n")
        f.write("\nnamespace trials_hd::diag {\n")
        f.write(f"const size_t kTracedCount = {len(traced)};\n")
        f.write(f"std::atomic<uint64_t> g_call_counts[{len(traced)}];\n")
        f.write(f"std::atomic<bool> g_capture_args[{len(traced)}];\n")
        f.write("const uint32_t kTracedAddresses[] = {\n")
        for i in range(0, len(traced), 8):
            f.write("    " + ", ".join(f"0x{a:08X}" for a in traced[i:i + 8]) + ",\n")
        f.write("};\n}  // namespace trials_hd::diag\n")
    print(f"wrote {len(traced)} shims to {out_path} ({len(overridden)} overridden functions skipped)")


if __name__ == "__main__":
    main()
